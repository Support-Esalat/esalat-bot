    async def send_broadcast(self, message):
        sent_count = 0
        try:
            async for dialog in self.client.iter_dialogs():
                if dialog.is_group:
                    try:
                        await self.client.send_message(dialog.id, message)
                        sent_count += 1
                        await asyncio.sleep(1)
                    except:
                        continue
        except:
            pass
        return sent_count


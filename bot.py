    def _migrate_old_tables(self):
        migrations = [
            ("lock_until", "group_settings", "TIMESTAMP"),
            ("mute_until", "members", "TIMESTAMP"),
            ("nickname", "members", "TEXT"),
            ("group_link", "group_settings", "TEXT"),
        ]
        for column_name, table_name, column_type in migrations:
            try:
                self.cursor.execute(f"SELECT {column_name} FROM {table_name} LIMIT 1")
            except sqlite3.OperationalError:
                try:
                    self.cursor.execute(f"ALTER TABLE {table_name} ADD COLUMN {column_name} {column_type}")
                    self.conn.commit()
                except:
                    pass
    

    def is_muted(self, user_id, chat_id):
        try:
            self.cursor.execute(
                "SELECT mute_until FROM members WHERE user_id = ? AND chat_id = ?",
                (user_id, chat_id)
            )
            result = self.cursor.fetchone()
            if result and result[0]:
                mute_until = datetime.fromisoformat(result[0]) if isinstance(result[0], str) else result[0]
                return mute_until > datetime.now()
        except:
            pass
        return False
    

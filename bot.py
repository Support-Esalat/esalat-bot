    async def clean_spam_tracker(self):
        while self.running:
            await asyncio.sleep(10)
            try:
                now = datetime.now()
                for key in list(self.spam_tracker.keys()):
                    self.spam_tracker[key] = [t for t in self.spam_tracker[key] if (now - t).total_seconds() < 5]
                    if not self.spam_tracker[key]:
                        del self.spam_tracker[key]
            except:
                pass
    
    async def check_subscription_expiry(self):
        while self.running:
            await asyncio.sleep(3600)
            try:
                self.db.cursor.execute(
                    "SELECT chat_id, expiry_date FROM subscriptions WHERE is_active = 1"
                )
                subscriptions = self.db.cursor.fetchall()
                for chat_id, expiry_date in subscriptions:
                    if isinstance(expiry_date, str):
                        expiry_date = datetime.fromisoformat(expiry_date)
                    if expiry_date <= datetime.now():
                        self.db.deactivate_subscription(chat_id)
                        try:
                            await self.client.send_message(
                                chat_id,
                                "📢 **اشتراک گروه به پایان رسید!**\n\nجهت تمدید با مدیریت تماس بگیرید."
                            )
                        except:
                            pass
            except:
                pass
    
    def check_spam(self, chat_id, user_id):
        key = f"{chat_id}:{user_id}"
        now = datetime.now()
        self.spam_tracker[key].append(now)
        recent = [t for t in self.spam_tracker[key] if (now - t).total_seconds() < 5]
        self.spam_tracker[key] = recent
        return len(recent) > 5
    
